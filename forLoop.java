import java.util.Scanner;

public class forLoop {
    public static void main(String[] args) {

        //print no.s 1 to 100
        for(int i=0;i<=100;i++){
            System.out.println(i);
        }

        //print no.s 1 to n

        Scanner in = new Scanner(System.in);
        int n = in.nextInt();
        for(int i=1;i<=n;i++){
            System.out.println(i);
        }






        
    }
}
